// The workspace instructions: `<master>/intent/workspace.md`, generated from the marker and the plugin's template
// (plugin/references/templates/workspace.md; workspace-single-repo.md in the single-repo layout), and its copy in
// `<workspace>/CLAUDE.md` (the repository's own `<master>/CLAUDE.md` in the single-repo layout), between the marker lines
// `<!-- ai-sdlc:start -->` and `<!-- ai-sdlc:end -->`. A session loads the CLAUDE.md of every folder above the one it
// starts in, so the copy reaches every session in the workspace; it is written out in full because a session in a
// product repository may never load an import from the master. Nothing outside the block is ever changed, and
// nothing is committed: the setup skill commits intent/workspace.md.
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CouldNotRun } from '../common/types.ts';
import type { Marker } from './marker.ts';

export const START = '<!-- ai-sdlc:start -->';
export const END = '<!-- ai-sdlc:end -->';
const TEMPLATE = fileURLToPath(new URL('../../references/templates/workspace.md', import.meta.url));
const TEMPLATE_SINGLE = fileURLToPath(new URL('../../references/templates/workspace-single-repo.md', import.meta.url));
const EXAMPLE_APP_ROW = '| <app> | `<folder>` | `intent/<system>/context/<app>.md` | `<check>` |';
const EXAMPLE_ROW ='| <system> | <repo>, <repo> | `<master>/intent/<system>/context/` | `<master>/intent/<system>/policies.md` |';

export type WorkspaceMdState = 'missing' | 'current' | 'stale' | 'written';
export type ClaudeMdState = 'current' | 'missing' | 'stale' | 'created' | 'updated' | 'home-folder' | 'bad-markers';
export type MarkerLine = { line: number; text: string };
export type InstructionsResult = { workspaceMd: WorkspaceMdState; claudeMd: ClaudeMdState; markerLines: MarkerLine[]; problems: string[] };

export type InstructionsInput = { workspace: string; master: string; masterName: string; marker: Marker; write: boolean; allowHome: boolean };

const RERUN = 'run the ai-sdlc setup skill with `--instructions`';
const NO_INSTRUCTIONS = `This workspace has no workspace instructions yet; ${RERUN}.`;
const OUT_OF_DATE = `The workspace instructions on this machine are missing or out of date; ${RERUN}.`;

/** The text of intent/workspace.md: the template with `<master>` and the systems table filled from the marker. */
export function workspaceText(template: string, masterName: string, marker: Marker): string {
  const systems = Object.entries(marker.systems);
  if (systems.length === 0) throw new CouldNotRun('the marker lists no system');
  if (marker.layout === 'single-repo') return singleRepoText(template, systems[0] as [string, Marker['systems'][string]]);
  const lines = template.replace(/\r\n?/g, '\n').replace(/\n*$/, '').split('\n');
  const at = lines.indexOf(EXAMPLE_ROW);
  if (at < 0) throw new CouldNotRun(`${TEMPLATE} has no example row for the systems table`);
  const filled = lines.map((l) => l.replaceAll('<master>', masterName));
  const rows = systems.map(([system, { repos }]) => {
    const list = repos.length > 0 ? repos.join(', ') : `all repositories except ${masterName}`;
    return `| ${system} | ${list} | \`${masterName}/intent/${system}/context/\` | \`${masterName}/intent/${system}/policies.md\` |`;
  });
  filled.splice(at, 1, ...rows);
  return filled.join('\n') + '\n';
}

/** The single-repo text: the one system and one row per app, with the staleness command for the app's folder. */
function singleRepoText(template: string, [system, { apps }]: [string, Marker['systems'][string]]): string {
  const lines = template.replace(/\r\n?/g, '\n').replace(/\n*$/, '').split('\n');
  const at = lines.indexOf(EXAMPLE_APP_ROW);
  if (at < 0) throw new CouldNotRun(`${TEMPLATE_SINGLE} has no example row for the apps table`);
  const rows = Object.entries(apps).map(([app, folder]) => {
    const check = `git rev-list --count <source_commit>..HEAD -- ${folder} ":(exclude)intent" ":(exclude).ai-sdlc.json"`;
    return `| ${app} | \`${folder}\` | \`intent/${system}/context/${app}.md\` | \`${check}\` |`;
  });
  lines.splice(at, 1, ...rows);
  return lines.join('\n').replaceAll('<system>', system) + '\n';
}

export function readTemplate(layout: Marker['layout'] = 'workspace'): string {
  const file = layout === 'single-repo' ? TEMPLATE_SINGLE : TEMPLATE;
  try {
    return readFileSync(file, 'utf8');
  } catch (e) {
    throw new CouldNotRun(`cannot read the workspace template ${file}: ${(e as Error).message}`);
  }
}

/** The line under the start marker. In the single-repo layout the master is the repository itself, so its path is bare. */
export const generatedLine = (masterName: string, single = false): string => `<!-- generated by ai-sdlc setup from ${single ? '' : `${masterName}/`}intent/workspace.md; edit outside this block -->`;

/** A text's lines, each with its own line ending, so the text outside the block is written back byte for byte. */
const linesOf = (text: string): string[] => text.match(/[^\n]*\n|[^\n]+$/g) ?? [];
const bare = (line: string): string => line.replace(/\r?\n$/, '');

export function markerLines(text: string): MarkerLine[] {
  return linesOf(text).flatMap((l, i) => {
    const t = bare(l).trim();
    return t === START || t === END ? [{ line: i + 1, text: bare(l) }] : [];
  });
}

/** The block's start and end line indexes, null when it has no marker, or 'bad' unless each is there once, in order. */
function blockAt(text: string): { start: number; end: number } | null | 'bad' {
  const found = markerLines(text);
  if (found.length === 0) return null;
  const starts = found.filter((m) => m.text.trim() === START);
  const ends = found.filter((m) => m.text.trim() === END);
  if (starts.length !== 1 || ends.length !== 1 || (starts[0] as MarkerLine).line > (ends[0] as MarkerLine).line) return 'bad';
  return { start: (starts[0] as MarkerLine).line - 1, end: (ends[0] as MarkerLine).line - 1 };
}

/** Text compared as the workspace reference says: line endings, blank lines at either end and trailing whitespace aside. */
const normalized = (text: string): string => text.replace(/\r\n?/g, '\n').split('\n').map((l) => l.trimEnd()).join('\n').replace(/^\n+|\n+$/g, '');

/** What the block holds after the generated line. */
function blockContent(text: string, at: { start: number; end: number }): string {
  const inner = linesOf(text).slice(at.start + 1, at.end);
  if (inner.length > 0 && bare(inner[0] as string).trim().startsWith('<!-- generated by ai-sdlc setup')) inner.shift();
  return inner.join('');
}

/** CLAUDE.md with the block written in: created, appended, or replaced between the marker lines. */
function withBlock(existing: string | null, generatedComment: string, workspaceMd: string): string {
  const inner = `${generatedComment}\n${workspaceMd}`;
  if (existing === null || existing === '') return `${START}\n${inner}${END}\n`;
  const at = blockAt(existing);
  if (at === null) {
    const ended = existing.endsWith('\n') ? existing : existing + '\n';
    return `${ended}\n${START}\n${inner}${END}\n`;
  }
  if (at === 'bad') throw new Error('unreachable: bad markers are refused before writing');
  const lines = linesOf(existing);
  const crlf = (lines[at.start] as string).endsWith('\r\n');
  const body = crlf ? inner.replace(/\n/g, '\r\n') : inner;
  return [...lines.slice(0, at.start + 1), body, ...lines.slice(at.end)].join('');
}

const real = (path: string): string => {
  try {
    return realpathSync.native(resolve(path));
  } catch {
    return resolve(path);
  }
};

const readOrNull = (path: string): string | null => (existsSync(path) ? readFileSync(path, 'utf8') : null);

function badMarkers(file: string, lines: MarkerLine[], wrote: boolean): string {
  const shown = lines.map((m) => `line ${m.line}: \`${m.text}\``).join(', ');
  return `${file} must hold each of \`${START}\` and \`${END}\` on its own line exactly once, start first, but the marker lines are ${shown}${wrote ? ', so it was left untouched' : ''}. Fix them and ${RERUN}.`;
}

export function instructions(input: InstructionsInput): InstructionsResult {
  const single = input.marker.layout === 'single-repo';
  const generated = workspaceText(readTemplate(input.marker.layout), input.masterName, input.marker);
  const mdFile = join(input.master, 'intent', 'workspace.md');
  const claudeFile = join(single ? input.master : input.workspace, 'CLAUDE.md');
  const md = readOrNull(mdFile);
  const claude = readOrNull(claudeFile);
  const found = claude === null ? [] : markerLines(claude);
  const atHome = !single && real(input.workspace) === real(homedir()) && !input.allowHome;
  const at = claude === null ? null : blockAt(claude);
  const problems: string[] = [];

  if (!input.write) {
    const workspaceMd: WorkspaceMdState = md === null ? 'missing' : md === generated ? 'current' : 'stale';
    if (workspaceMd === 'missing') problems.push(NO_INSTRUCTIONS);
    if (workspaceMd === 'stale') problems.push(`${mdFile} is out of date with .ai-sdlc.json; ${RERUN}.`);
    let claudeMd: ClaudeMdState;
    if (atHome) claudeMd = 'home-folder';
    else if (md === null || at === null) claudeMd = 'missing';
    else if (at === 'bad') claudeMd = 'bad-markers';
    else claudeMd = normalized(blockContent(claude as string, at)) === normalized(md) ? 'current' : 'stale';
    if (claudeMd === 'bad-markers') problems.push(badMarkers(claudeFile, found, false));
    else if ((claudeMd === 'missing' || claudeMd === 'stale') && md !== null) problems.push(OUT_OF_DATE);
    return { workspaceMd, claudeMd, markerLines: found, problems };
  }

  let workspaceMd: WorkspaceMdState = 'current';
  if (md !== generated) {
    mkdirSync(dirname(mdFile), { recursive: true });
    writeFileSync(mdFile, generated);
    workspaceMd = 'written';
  }
  let claudeMd: ClaudeMdState;
  if (atHome) {
    claudeMd = 'home-folder';
    problems.push(`The workspace folder ${input.workspace} is the home folder, where a CLAUDE.md applies to every project under it, so ${claudeFile} was left untouched. Ask the engineer, and with their agreement rerun with \`--allow-home\`.`);
  } else if (at === 'bad') {
    claudeMd = 'bad-markers';
    problems.push(badMarkers(claudeFile, found, true));
  } else {
    const next = withBlock(claude, generatedLine(input.masterName, single), generated);
    if (next === claude) claudeMd = 'current';
    else {
      writeFileSync(claudeFile, next);
      claudeMd = claude === null ? 'created' : 'updated';
    }
  }
  return { workspaceMd, claudeMd, markerLines: claude === null || claudeMd === 'current' || claudeMd === 'bad-markers' ? found : markerLines(readFileSync(claudeFile, 'utf8')), problems };
}
